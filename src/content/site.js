// Заливки экранов идут по кругу, чтобы ряд не выглядел одинаковым.
const SCREEN_FILLS = ['tint', 'blue', 'grey'];

// Короткое имя проекта для рядов на главной: всё, что стоит до запятой в
// заголовке. Полный заголовок остаётся в списке кейсов и в разметке для
// поисковиков, там он и работает.
CASES.items.forEach((item) => {
  item.name = item.title.split(',')[0];
  item.screens = (SCREENS[item.slug] || []).map((title, i) => ({
    title,
    fill: SCREEN_FILLS[i % SCREEN_FILLS.length],
  }));
});

// Снятые кейсы отсекаются один раз здесь, поэтому дальше их не видит никто.
// Ни список, ни счётчик, ни фильтры, ни лента на главной, ни переход к
// соседнему проекту, ни карта сайта. Прямой адрес такого кейса открывает
// страницу «Такого кейса нет», потому что findCase ищет по этому же списку.
CASES.items = CASES.items.filter((c) => !c.hidden);

// Вкладки собираются из самих кейсов: пустых направлений в фильтре не будет.
CASES.filters = ['все', ...Array.from(new Set(CASES.items.map((c) => c.group)))];

// На главной три кейса подряд, остальные на /cases. Ряд занимает целый
// экран на кейс, больше трёх туда не ставится.
export const FEATURED_CASES = CASES.items.slice(0, 3);

export function findCase(slug) {
  return CASES.items.find((c) => c.slug === slug) || null;
}

export function neighbourCases(slug) {
  const i = CASES.items.findIndex((c) => c.slug === slug);
  if (i < 0) return { prev: null, next: null };
  return {
    prev: CASES.items[i - 1] || CASES.items[CASES.items.length - 1],
    next: CASES.items[i + 1] || CASES.items[0],
  };
}

