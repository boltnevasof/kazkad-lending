export function findCase(slug) {
  return CASES.items.find((c) => c.slug === slug) || null;
}

export function neighbourCases(slug) {
  const i = CASES.items.findIndex((c) => c.slug === slug);
  if (i < 0) return { prev: null, next: null };
  return {
    prev: CASES.items[i - 1] || CASES.items[CASES.items.length - 1],
    next: CASES.items[i + 1] || CASES.items[0],
  };
}

